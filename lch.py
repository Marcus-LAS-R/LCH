    def unload(self):
        """Removes the plugin menu item and icon from QGIS GUI."""

        if self.menu is not None:
            self.iface.mainWindow().menuBar().removeAction(
                self.menu.menuAction())
        for a in self.akcje_toolbara:
            self.iface.removeToolBarIcon(a)
        del self.toolbar

