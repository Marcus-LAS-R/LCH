    def ustaw_mape(self):
        m = ustaw_mape.UstawMape(self.iface)
        if not m.sprawdz_warstwy():
            return
        if not m.znajdz_bazy():
            return
        m.pobierz_meta()
        m.zmien_meta_data()
        if not m.przesun_elem():
            return
        ustaw_mape.zapisz_z_przyrostkiem_ark(self.iface, m)

